    #[test]
    fn convert_rgb24_to_rgb565_little_rgb() {
        // two pixels: red and blue
        let src = vec![255u8, 0, 0, 0, 0, 255u8];
        let out =
            super::convert_rgb24_to_bpp_format(&src, 2, 1, 2, Endianness::Little, ColorOrder::RGB)
                .unwrap();
        // red -> 0xF800 -> little [0x00, 0xF8]
        assert_eq!(&out[0..2], &[0x00, 0xF8]);
        // blue -> 0x001F -> little [0x1F, 0x00]
        assert_eq!(&out[2..4], &[0x1F, 0x00]);
    }

    #[test]
    fn convert_rgb24_to_rgb565_big_bgr() {
        // two pixels: red and blue
        let src = vec![255u8, 0, 0, 0, 0, 255u8];
        // big-endian + BGR
        let out =
            super::convert_rgb24_to_bpp_format(&src, 2, 1, 2, Endianness::Big, ColorOrder::BGR)
                .unwrap();
        // For BGR order red (255,0,0) maps to low bits (r5 at LSB), result = 0x001F -> BE [0x00,0x1F]
        assert_eq!(&out[0..2], &[0x00, 0x1F]);
        // For blue (0,0,255) with BGR -> high bits (b5 << 11) => 0xF800 -> BE [0xF8, 0x00]
        assert_eq!(&out[2..4], &[0xF8, 0x00]);
    }

    #[test]
    fn convert_rgb24_format_big_endian_bgr() {
        // src two pixels: [R,G,B] pairs
        let src = vec![0x01u8, 0x02u8, 0x03u8, 0x11u8, 0x12u8, 0x13u8];
        // Order BGR, Big-endian: per-pixel bytes are reversed after reordering -> [0, R, G, B] reversed -> [B,G,R,0]
        let out =
            super::convert_rgb24_to_bpp_format(&src, 2, 1, 4, Endianness::Big, ColorOrder::BGR)
                .unwrap();
        assert_eq!(out.len(), 8);
        // first pixel: bytes reversed of [B,G,R,0] -> [0,R,G,B]? Wait, our function reverses bytes for big endian, so initial bytes are [B,G,R,0] then reversed => [0,R,G,B]
        // So for src pixel (0x01,0x02,0x03) with BGR initial -> [0x03,0x02,0x01,0x00], reversed -> [0x00,0x01,0x02,0x03]
        assert_eq!(&out[0..4], &[0x00, 0x01, 0x02, 0x03]);
        // second pixel
        assert_eq!(&out[4..8], &[0x00, 0x11, 0x12, 0x13]);
    }

